import { TemplateService, templateService } from './templateService';
import { BankPattern, OCRResult } from '../types/ocr';

export class LocalLearningService {
  private readonly templateService: TemplateService;

  constructor() {
    this.templateService = templateService;
  }

  async learnFromCorrection(params: { ocrResult: OCRResult; correctNumber: string; bankId: string }): Promise<boolean> {
    const { ocrResult, correctNumber, bankId } = params;

    if (!ocrResult.rawText.includes(correctNumber)) {
      console.log('No se puede generar pattern: número no encontrado en texto');
      return false;
    }

    const newPattern = this.generatePattern(ocrResult.rawText, correctNumber);
    if (newPattern) {
      await this.templateService.addPattern(bankId, newPattern);
      console.log('Nuevo pattern aprendido:', newPattern.regex);
      return true;
    }

    return false;
  }

  private generatePattern(text: string, number: string): BankPattern | null {
    const index = text.indexOf(number);
    if (index === -1) return null;

    const before = text.substring(Math.max(0, index - 30), index).trim();
    const words = before.split(/\s+/).slice(-2);

    if (words.length === 0) return null;

    const prefix = words
      .map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
      .join('\\s+');

    return {
      regex: `${prefix}\\s*[:.-]?\\s*(\\d{${number.length},})`,
      priority: 7,
      description: `Auto: "${words.join(' ')}" + número`,
      successCount: 1,
      autoGenerated: true,
    };
  }
}

export const localLearningService = new LocalLearningService();

