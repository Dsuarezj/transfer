export interface BoundingBox {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface OCRResult {
  number: string | null;
  confidence: number;
  bankDetected: string | null;
  region: BoundingBox | null;
  rawText: string;
  processingTime: number;
}

export interface BankPattern {
  regex: string;
  priority: number;
  description: string;
  successCount: number;
  autoGenerated?: boolean;
}

export interface BankTemplate {
  id: string;
  name: string;
  keywords: string[];
  patterns: BankPattern[];
  preprocessing: {
    contrast: number;
    brightness: number;
    grayscale: boolean;
  };
  examples: string[];
  stats: {
    totalAttempts: number;
    successfulDetections: number;
    lastUpdated: string;
  };
}

